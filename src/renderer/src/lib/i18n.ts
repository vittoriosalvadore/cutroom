/** Values substituted into `{name}` placeholders (e.g. t('{n} clips selected', { n: 3 })). */
export type Vars = Record<string, string | number>

/**
 * Fill `{name}` placeholders from `vars`. Unknown placeholders are left as-is
 * (visible, so a typo shows up instead of silently vanishing). Placeholders are
 * part of the English key, so translations must keep the same `{name}`s.
 */
export function interpolate(text: string, vars?: Vars): string {
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m))
}

/**
 * Like interpolate, but the values may be non-strings (e.g. React elements) so a
 * placeholder can render as markup — bold, a link — wherever the language puts
 * it. Returns the text split into parts, with each `{name}` replaced by its
 * value; unknown placeholders stay literal text. Give element values a `key`.
 */
export function interpolateParts<T>(text: string, vars: Record<string, T>): (string | T)[] {
  const out: (string | T)[] = []
  let last = 0
  for (const m of text.matchAll(/\{(\w+)\}/g)) {
    if (!(m[1] in vars)) continue
    if (m.index > last) out.push(text.slice(last, m.index))
    out.push(vars[m[1]])
    last = m.index + m[0].length
  }
  if (last < text.length) out.push(text.slice(last))
  return out
}

/** Translate a key into `lang` (English fallback), filling any `{name}` placeholders. */
export function translate(key: string, lang: Lang, vars?: Vars): string {
  const text = lang === 'en' ? key : STRINGS[lang]?.[key] ?? key
  return interpolate(text, vars)
}

/** Non-React translate using the current language from settings. */
export function t(key: string, vars?: Vars): string {
  return translate(key, useSettings.getState().language, vars)
}

/** React hook: a translator bound to the current language (re-renders on change). */
export function useT(): (key: string, vars?: Vars) => string {
  const lang = useSettings((s) => s.language)
  return (key: string, vars?: Vars) => translate(key, lang, vars)
}

/** The translation table for one language (tests use it to check coverage). */
export function dictionary(lang: Exclude<Lang, 'en'>): Readonly<Record<string, string>> {
  return STRINGS[lang]
}
